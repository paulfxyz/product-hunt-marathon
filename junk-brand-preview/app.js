// COPY COMMAND
// ─────────────────────────────────────────────────────────────────────────────
function copyCmd(btn, text) {
  navigator.clipboard.writeText(text).then(() => {
    const orig = btn.textContent;
    btn.textContent = 'Copied!';
    btn.style.color = '#22c55e';
    setTimeout(() => { btn.textContent = orig; btn.style.color = ''; }, 2000);
  }).catch(() => {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    document.body.removeChild(ta);
  });
}

// ─────────────────────────────────────────────────────────────────────────────
// SCROLL REVEAL
// ─────────────────────────────────────────────────────────────────────────────
// rootMargin: '0px 0px 60px 0px' — trigger 60px BEFORE the element reaches
// the bottom of the viewport (positive bottom margin = earlier trigger).
// threshold: 0.05 — fire as soon as 5% of the element is visible.
// Fallback: if IntersectionObserver is not available or never fires (e.g. some
// headless environments), reveal all elements after 400ms as a safety net.
const _revealAll = () =>
  document.querySelectorAll('.reveal').forEach(el => el.classList.add('revealed'));

if (!('IntersectionObserver' in window)) {
  _revealAll();
} else {
  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach(e => {
      if (e.isIntersecting) {
        e.target.classList.add('revealed');
        revealObserver.unobserve(e.target);
      }
    });
  }, { threshold: 0.05, rootMargin: '0px 0px 60px 0px' });

  document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));

  // Safety-net fallback: after 1.2s, reveal anything still hidden.
  // Covers cases where the observer fires but some elements never intersect
  // (e.g. elements already in viewport at page load before observer attached).
  setTimeout(() => _revealAll(), 1200);
}
