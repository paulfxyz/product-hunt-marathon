// LANGUAGE FLAG MODAL
// Full-screen modal with all 30+ languages, grouped with flags
// ─────────────────────────────────────────────────────────────────────────────
function buildLangModal() {
  // Remove existing if any
  const existing = document.getElementById('lang-modal-overlay');
  if (existing) existing.remove();

  const overlay = document.createElement('div');
  overlay.id = 'lang-modal-overlay';
  overlay.setAttribute('role', 'dialog');
  overlay.setAttribute('aria-modal', 'true');
  overlay.setAttribute('aria-label', 'Select language');

  const modal = document.createElement('div');
  modal.className = 'lang-modal';

  const header = document.createElement('div');
  header.className = 'lang-modal-header';
  header.innerHTML = `
    <h2 class="lang-modal-title">🌍 Choose your language</h2>
    <button class="lang-modal-close" aria-label="Close language selector">
      <svg width="12" height="12" viewBox="0 0 12 12" fill="none">
        <path d="M1 1l10 10M11 1L1 11" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"/>
      </svg>
    </button>
  `;

  const grid = document.createElement('div');
  grid.className = 'lang-modal-grid';

  Object.entries(TRANSLATIONS).forEach(([code, t]) => {
    const btn = document.createElement('button');
    btn.className = 'lang-modal-item' + (code === currentLang ? ' active' : '');
    btn.setAttribute('data-lang', code);
    btn.innerHTML = `<span class="lang-modal-flag">${t.flag}</span><span class="lang-modal-name">${t.name}</span>`;
    btn.addEventListener('click', () => {
      applyLang(code);
      closeLangModal();
    });
    grid.appendChild(btn);
  });

  modal.appendChild(header);
  modal.appendChild(grid);
  overlay.appendChild(modal);
  document.body.appendChild(overlay);

  // Close on overlay click
  overlay.addEventListener('click', (e) => {
    if (e.target === overlay) closeLangModal();
  });

  // Close button
  modal.querySelector('.lang-modal-close').addEventListener('click', closeLangModal);

  // Open with animation
  requestAnimationFrame(() => {
    requestAnimationFrame(() => {
      overlay.classList.add('open');
    });
  });

  // Focus close button
  setTimeout(() => modal.querySelector('.lang-modal-close').focus(), 60);
}

function closeLangModal() {
  const overlay = document.getElementById('lang-modal-overlay');
  if (!overlay) return;
  overlay.classList.remove('open');
  overlay.addEventListener('transitionend', () => overlay.remove(), { once: true });
}

