'use strict';

// ─────────────────────────────────────────────────────────────────────────────
// SCRAMBLE / TYPO EFFECT
// Subtle character scramble on the hero title. Cycles through random chars
// for each position before resolving to the real letter. Inspired by the
// hacker-aesthetic typo effect on paulfleury.com — kept very short and calm.
//
// FIX (v3.1.7): Previous version read el.textContent as the "final" text,
// which included raw \n characters from the HTML source. When innerHTML was
// then written with those raw \n chars (not replaced with <br>), the line
// breaks were lost — the title appeared as one run-on line.
//
// The correct approach: store the final text in data-final as the plain
// multi-line string, and always use .replace(/\n/g, '<br>') when writing
// back to innerHTML.
// ─────────────────────────────────────────────────────────────────────────────
const SCRAMBLE_CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%&';

function scrambleText(el, finalText, duration = 700) {
  // finalText may contain literal \n — we split on those to handle line breaks.
  // During scramble we render random chars; spaces and \n are left as-is.
  const chars = finalText.split('');
  const totalFrames = Math.floor(duration / 40); // ~25fps
  let frame = 0;

  const tick = () => {
    const progress = frame / totalFrames; // 0 → 1
    const resolved = Math.floor(progress * chars.length);

    const out = chars.map((ch, i) => {
      if (ch === '\n' || ch === ' ') return ch; // preserve whitespace exactly
      if (i < resolved) return ch;              // already resolved to real char
      // Still scrambling — pick a random printable char
      return SCRAMBLE_CHARS[Math.floor(Math.random() * SCRAMBLE_CHARS.length)];
    });

    // Replace \n with <br> so the line break renders in HTML
    el.innerHTML = out.join('').replace(/\n/g, '<br>');

    frame++;
    if (frame <= totalFrames) requestAnimationFrame(tick);
    else el.innerHTML = finalText.replace(/\n/g, '<br>'); // settle to clean final state
  };

  requestAnimationFrame(tick);
}

// Run scramble once on page load (after a tiny delay so font is ready)
document.addEventListener('DOMContentLoaded', () => {
  const el = document.querySelector('.scramble');
  if (!el) return;

  // data-final is set in the HTML via data-i18n; fall back to textContent
  // Normalise: trim, collapse multiple spaces, preserve intentional \n
  const raw = (el.dataset.final || el.textContent || '').trim();
  el.dataset.final = raw;

  setTimeout(() => scrambleText(el, raw, 650), 300);
});

